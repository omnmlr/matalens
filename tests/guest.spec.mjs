test('rights reminders rotate, pause and disclose, and both party exercises are usable', async ({ page }) => {
  await page.clock.install()
  await page.goto('/rights')
  const carousel = page.getByRole('group', { name: 'Voting rights reminders' })
  await carousel.scrollIntoViewIfNeeded()
  await expect(carousel.getByRole('heading')).toHaveText('Your ballot is private.')
  await page.waitForTimeout(100)
  await page.clock.fastForward(7600)
  await expect(carousel.getByRole('heading')).toHaveText('Ask for voting assistance.')
  const pause = carousel.getByRole('button', { name: 'Pause reminders' })
  await pause.click()
  await page.mouse.move(2, 2)
  await page.clock.fastForward(7600)
  await expect(carousel.getByRole('heading')).toHaveText('Ask for voting assistance.')
  await carousel.getByRole('button', { name: 'Next reminder' }).click()
  await carousel.getByRole('button', { name: 'What you can do' }).click()
  await expect(carousel.getByText('What you can do.', { exact: true })).toBeVisible()
  await expect(carousel.getByRole('link', { name: /Electoral Act 2026 · Section 56/ })).toHaveAttribute('href', 'https://nass.gov.ng/documents/download/11248')
  await expect(page).toHaveURL(/\/rights$/)
  await page.goto('/rights')
  await page.getByLabel('Search rights guides').fill('intimidation')
  await page.locator('summary').filter({ hasText: 'Voter safety' }).click()
  await expect(page.getByText('Move to a safer place. Avoid confrontation.', { exact: false })).toBeVisible()
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/rights')
  await page.clock.fastForward(12000)
  await expect(carousel.getByRole('heading')).toHaveText('Your ballot is private.')

  await page.goto('/parties')
  await page.getByLabel('Party name or abbreviation').fill('Labour Party')
  await expect(page.getByRole('link', { name: /Labour Party LP/ })).toBeVisible()
  await page.getByRole('link', { name: 'Start Know Your Party' }).click()
  await page.getByRole('button', { name: /Recognize party symbols/ }).click()
  const mapping = {
    'A star': 'AA', 'A handshake': 'ADC', 'A broom': 'APC',
    'A rooster': 'APGA', 'People inside a wheel': 'LP', 'An umbrella': 'PDP',
  }
  for (let index = 0; index < Object.keys(mapping).length; index++) {
    const clue = await page.locator('.party-clue strong').textContent()
    await page.getByRole('radio', { name: new RegExp('\\(' + mapping[clue] + '\\)$') }).check()
    await page.getByRole('button', { name: 'Check answer' }).click()
    await expect(page.getByRole('status')).toContainText('That’s right.')
    await expect(page.getByRole('link', { name: 'Read the source' })).toBeVisible()
    await page.getByRole('button', { name: index === 5 ? 'See my score' : 'Next question' }).click()
  }
  await expect(page.getByRole('heading', { name: 'You got 6 of 6 right.' })).toBeVisible()
  await page.getByRole('button', { name: 'All exercises' }).click()
  await page.getByRole('button', { name: /Match a candidate to a party/ }).click()
  await expect(page.getByRole('heading', { name: /2027 presidential candidate/ })).toBeVisible()
  await page.getByRole('radio').first().check()
  await page.getByRole('button', { name: 'Check answer' }).click()
  await expect(page.getByRole('status')).toContainText('for the 2027 presidential election.')
})
